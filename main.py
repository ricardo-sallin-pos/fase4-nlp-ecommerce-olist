import re
import unicodedata

# Mapa de contrações comuns em PT-BR informal
CONTRACTIONS = {
  "vc": "você", "tb": "também", "tbm": "também",
  "pq": "por que", "obg": "obrigado", "blz": "beleza",
  "td": "tudo", "bjs": "beijos", "vlw": "valeu",
  "n": "não", "naum": "não",
}


def limpar_normalizar(texto: str,
                      remove_acentos: bool = False) -> str:
  """Pipeline de limpeza e normalização para texto em PT-BR.
  Args:
  texto: string com texto bruto
  remove_acentos: True só se downstream exige (busca, BoW agressivo)
  """
  if not isinstance(texto, str):
    return ""
  # 1. Lowercase
  texto = texto.lower()

  # 2. Transforma pontos finais consecutivos (ex: .., ..., ....) em um único ponto final
  texto = re.sub(r"\.{2,}", ".", texto)

  # 3. corrige ponto final sem espaço, exceto ".com" ou ".br"
  texto = re.sub(r"\.(?!(?:com|br)\b)(?=[a-záàâãäéèêëíìîïóòôõöúùûüç])", ". ", texto)

  # 4. Remove HTML residual
  texto = re.sub(r"<[^>]+>", " ", texto)

  # 4. Remove URLs e e-mails
  texto = re.sub(r"http\S+|www\.\S+", " ", texto)
  texto = re.sub(r"\S+@\S+", " ", texto)

  # 5. Expande contrações simples (palavra inteira)
  palavras = texto.split()
  palavras = [CONTRACTIONS.get(p, p) for p in palavras]
  texto = " ".join(palavras)

  # 6. Remove caracteres não úteis (mantém letras, espaço e algumas pontuações)
  texto = re.sub(r"[^a-záàâãäéèêëíìîïóòôõöúùûüç\s.,!?]", " ", texto)

  # 7. Opcional: remover acentos
  if remove_acentos:
    nfkd = unicodedata.normalize("NFKD", texto)
    texto = "".join(c for c in nfkd if not unicodedata.combining(c))

  # 8. Colapsa espaços múltiplos
  texto = re.sub(r"\s+", " ", texto).strip()
  return texto

