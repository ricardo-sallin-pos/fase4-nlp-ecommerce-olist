def report_IA(response):
  prompt = ''
  model = ''
  tools = []
  input_tokens = 0
  output_tokens = 0
  resposta = ''
  for msg in response.get("messages"):
      if isinstance(msg, langchain_core.messages.human.HumanMessage):
          prompt = msg.content
      if isinstance(msg, langchain_core.messages.tool.ToolMessage):
          tools.append(msg.content)
      if isinstance(msg, langchain_core.messages.ai.AIMessage):
          model = msg.response_metadata.get("model_name", "")
          input_tokens += msg.usage_metadata.get("input_tokens", 0)
          output_tokens += msg.usage_metadata.get("output_tokens", 0)
