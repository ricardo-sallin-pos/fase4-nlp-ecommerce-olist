stopwords_ptbr_exceto_nao = set(STOP_WORDS_PT) - {"não"}
stemmer = RSLPStemmer()

def pipeline_nlp(texto: str,
                 lemma: bool = False,
                 remove_naos: bool = False) -> list[str]:
  """
  Recebe texto em PT, devolve lista de tokens limpos.
  lemma: se True, usa lemmatization, se False, stemming.
  remove_nao: se True, os "nãos" caem, senão ficam
  """
  # 1) limpa e normaliza
  texto = limpar_normalizar(texto)
  # 2) tokeniza
  tokens = word_tokenize(texto, language="portuguese")
  # 3) remove stop words e tokens muito curtos
  sw = STOP_WORDS_PT if remove_naos else stopwords_ptbr_exceto_nao
  tokens = [t for t in tokens if t not in sw and len(t) > 2]
  # 4) remove tokens repetidos preservando a ordem original
  tokens = list(dict.fromkeys(tokens))
  # 5) aplica stemming/lemmatization
  if lemma:
    tokens = [token.lemma_ for token in nlp(" ".join(tokens))]
  else:
    tokens = [stemmer.stem(t) for t in tokens]
  return tokens

